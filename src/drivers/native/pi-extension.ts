/**
 * ama 给每次 pi 运行加载的扩展（`-e <文件>`，#198 审批闸，#254 并入桥）：驱动与 ACP 桥共用，源码固定。
 *
 * pi 自己没有审批通道，所以扩展做三件事：
 * 1. **审批闸**：只读内置工具以外的每次工具调用，经 RPC 的扩展对话框（`extension_ui_request{confirm}`，
 *    标题 {@link PI_GATE_TITLE}，正文 JSON `{id, tool, input, readOnly, parent?}`）交给 ama；ama 按模式决定直接
 *    拒绝、直接放行或交给人。`readOnly` 取自工具的 `annotations.readOnlyHint`（MCP 工具带服务器声明的值）。
 *    被拒绝时再用 editor 对话框（标题 {@link PI_REASON_TITLE}，预填工具调用 id）向 ama 取一句理由，作为
 *    阻止原因回给模型（plan 模式借此告诉模型“现在只许只读”）；取不到用默认句。
 * 2. **MCP 透传**：读 `AMA_BRIDGE_CONFIG` 指向的 `bridge.json`，对 `mcpServers` 的每一项调用
 *    `pi.registerMcpServer(name, { …, exposure: "direct" })`——ama 自己不说 MCP，连接由 Pi 内置的 MCP 做。
 *    没有这个环境变量（驱动）时什么也不注册。
 * 3. **能力报告**：`session_start` 时用 fire-and-forget 的 `setStatus`（键 {@link PI_STATUS_KEY}，正文 JSON
 *    `{tools, mcpFailures}`）告诉 ama 当前有哪些工具、哪些 MCP 注册失败。
 *
 * 文件写在每个会话自己的临时目录（`mkdtemp`，目录与文件只有当前用户可读写），会话关闭时整目录删除；
 * 不写 pi 的配置目录，不改用户的扩展设置。扩展源码只用纯 JS 语法（pi 用 jiti 加载）。
 */

import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

/** 审批对话框标题：ama 只认这个标题的 confirm，其它扩展的对话框一律取消（不代答）。 */
export const PI_GATE_TITLE = "ama-approval";

/** 取拒绝理由的 editor 对话框标题。 */
export const PI_REASON_TITLE = "ama-reason";

/** 能力报告的 `setStatus` 键。 */
export const PI_STATUS_KEY = "ama-bridge";

/** 指向 `bridge.json` 的环境变量名。 */
export const PI_CONFIG_ENV = "AMA_BRIDGE_CONFIG";

/** pi 不经审批就放行的内置只读工具。 */
export const PI_READ_ONLY_TOOLS: readonly string[] = ["read", "grep", "find", "ls"];

/** 扩展源码（固定，不含时间与随机数）。 */
export const PI_EXTENSION_SOURCE = `// Generated by ama for one pi run: approval gate, MCP hand-over, capability report.
import { readFileSync } from "node:fs";
const READ_ONLY = new Set(${JSON.stringify(PI_READ_ONLY_TOOLS)});
function readConfig() {
  const file = process.env[${JSON.stringify(PI_CONFIG_ENV)}];
  if (!file) return {};
  try {
    return JSON.parse(readFileSync(file, "utf8"));
  } catch {
    return {};
  }
}
export default function (pi) {
  const config = readConfig();
  const failures = [];
  if (typeof pi.registerMcpServer === "function") {
    for (const [name, server] of Object.entries(config.mcpServers || {})) {
      try {
        pi.registerMcpServer(name, Object.assign({}, server, { exposure: "direct" }));
      } catch (error) {
        failures.push(name + ": " + (error && error.message ? error.message : String(error)));
      }
    }
  }
  const allTools = () => (typeof pi.getAllTools === "function" ? pi.getAllTools() : []);
  pi.on("session_start", async (_event, ctx) => {
    ctx.ui.setStatus(
      ${JSON.stringify(PI_STATUS_KEY)},
      JSON.stringify({ tools: allTools().map((tool) => tool.name), mcpFailures: failures }),
    );
  });
  pi.on("tool_call", async (event, ctx) => {
    if (READ_ONLY.has(event.toolName)) return undefined;
    const tool = allTools().find((candidate) => candidate.name === event.toolName);
    const hints = tool && tool.annotations;
    const ok = await ctx.ui.confirm(
      ${JSON.stringify(PI_GATE_TITLE)},
      JSON.stringify({
        id: event.toolCallId,
        tool: event.toolName,
        input: event.input,
        readOnly: Boolean(hints && hints.readOnlyHint === true),
        parent: event.parentToolCallId,
      }),
    );
    if (ok) return undefined;
    let reason = "";
    try {
      reason = (await ctx.ui.editor(${JSON.stringify(PI_REASON_TITLE)}, event.toolCallId)) || "";
    } catch {
      reason = "";
    }
    return { block: true, reason: reason || event.toolName + " was not approved by the user" };
  });
}
`;

export interface PiExtensionFiles {
  /** 扩展文件（`-e` 的参数）。 */
  path: string;
  /** `bridge.json`（`AMA_BRIDGE_CONFIG` 的值）；没有配置时不写。 */
  configPath: string | undefined;
  dispose(): void;
}

/** 写一份扩展（与可选的 `bridge.json`），返回路径与清理函数。 */
export function writePiExtension(config?: Record<string, unknown>): PiExtensionFiles {
  const dir = mkdtempSync(join(tmpdir(), "ama-pi-"));
  const path = join(dir, "ama-bridge.ts");
  writeFileSync(path, PI_EXTENSION_SOURCE, { mode: 0o600 });
  let configPath: string | undefined;
  if (config !== undefined) {
    configPath = join(dir, "bridge.json");
    writeFileSync(configPath, JSON.stringify(config), { mode: 0o600 });
  }
  return { path, configPath, dispose: () => rmSync(dir, { recursive: true, force: true }) };
}
